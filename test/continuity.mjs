import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createService, initialize} from '../src/standalone/service.mjs';
import {createBackupTo, restoreBackupFile} from '../src/standalone/backup.mjs';

test('continuity survives restart and opt-in restore while ordinary backup omits role notes', async t => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'vec-continuity-'));
  const root = path.join(temp, 'service');
  const token = initialize(root);
  let service = createService({root});
  t.after(async () => {
    await service.close();
    fs.rmSync(temp, {recursive:true,force:true});
  });
  const call = (path, body) => service.handle({path:'/api/v1/' + path, method:'POST', token, body});
  await call('admin/projects', {projectId:'p'});
  const reader = (await call('admin/projects', {projectId:'reader'})).body.token;
  await call('admin/spaces', {spaceId:'s', owner:'p'});
  const scope = {kind:'private',id:'a'};
  const group = {kind:'group',id:'g'};
  const role = {scope,roleId:'moon'};
  const message = {messageId:'m', scope, conversationId:'a', actorId:'alice', role:'user',
    text:'Continue picking a book next time', timestamp:1700000000000};
  assert.equal((await call('spaces/s/messages',{messages:[message]})).body.accepted,1);
  const note = {...role, operationId:'note', text:'Pick a book', messageId:'m'};
  assert.equal((await call('spaces/s/role-notes',note)).status,200);
  assert.equal((await call('spaces/s/role-notes',note)).body.replayed,true);
  const writeRole = body => call('spaces/s/role-notes', {...role, ...body});
  const at = message.timestamp;
  assert.equal((await writeRole({kind:'concern',operationId:'concern',text:'Worried about the deadline',messageId:'m'})).status,200);
  assert.equal((await writeRole({kind:'day',dayKind:'occurred',at,operationId:'no-evidence',text:'Visited the library'})).status,400);
  assert.equal((await writeRole({kind:'day',dayKind:'occurred',at,operationId:'wrong-chat',text:'Visited the library',messageId:'m',scope:group})).status,400);
  assert.equal((await writeRole({kind:'day',dayKind:'fictional',at:at + 1,operationId:'fiction',text:'Visited the moon'})).status,200);
  assert.equal((await writeRole({kind:'day',dayKind:'planned',at,operationId:'plan',text:'Visit the library'})).status,200);
  const event = {messageId:'visit',scope,conversationId:'a',actorId:'alice',role:'user',
    text:'We visited the library',timestamp:at + 2};
  assert.equal((await call('spaces/s/messages',{messages:[event]})).body.accepted,1);
  const recall = async () => (await call('spaces/s/recall',{scope,query:'library',mode:'keyword'})).body.items;
  const recallBefore = await recall();
  assert.ok(recallBefore.length > 0);
  const occurrence = {id:'plan',expectedRevision:1,operationId:'visited',dayKind:'occurred',at:at + 2,messageId:'visit'};
  assert.equal((await writeRole({...occurrence,id:'fiction'})).status,400);
  assert.equal((await writeRole(occurrence)).body.revision,2);
  assert.equal((await writeRole(occurrence)).body.replayed,true);
  assert.equal((await writeRole({...occurrence,operationId:'stale'})).status,409);
  assert.equal((await writeRole({id:'concern',operationId:'resolve',expectedRevision:1,status:'completed'})).status,200);
  const readerQuery = () => service.handle({path:'/api/v1/spaces/s/role-notes/query',method:'POST',token:reader,body:{...role,kind:'day'}});
  const setReaders = projectIds => service.handle({path:'/api/v1/admin/spaces/s/readers',method:'PUT',token,body:{projectIds}});
  assert.equal((await readerQuery()).status,403);
  assert.deepEqual(await recall(),recallBefore);
  assert.equal((await setReaders(['reader'])).status,200);
  assert.equal((await readerQuery()).body.items.length,2);
  assert.equal((await setReaders([])).status,200);
  assert.equal((await readerQuery()).status,403);
  assert.equal((await call('spaces/s/continuity-tasks',{...note,scope:group})).status,400);
  assert.equal((await call('spaces/s/continuity-tasks',{scope,operationId:'task',text:note.text,messageId:'m'})).status,200);
  await service.close();
  for (const [includeRoleNotes, sid] of [[false, 'plain'], [true, 'with-role']]) {
    const file = path.join(temp,sid+'.vmb');
    await createBackupTo(root,file,{spaceId:'s',mode:'full',includeRoleNotes});
    await restoreBackupFile(file,path.join(root,'spaces',sid));
  }
  const accessFile = path.join(root,'access.json');
  const access = JSON.parse(fs.readFileSync(accessFile));
  access.spaces.plain = access.spaces['with-role'] = access.spaces.s;
  fs.writeFileSync(accessFile,JSON.stringify(access));
  service = createService({root});
  const entries = async (sid, endpoint, body) => (await call('spaces/'+sid+'/'+endpoint+'/query',body)).body.items;
  assert.equal((await entries('plain','role-notes',role)).length,0);
  assert.deepEqual((await entries('with-role','role-notes',role)).map(item => item.sourceRefs[0].id),['m']);
  assert.deepEqual(await entries('plain','role-notes',{...role,kind:'day'}),[]);
  assert.deepEqual(await entries('plain','role-notes',{...role,kind:'concern',status:'all'}),[]);
  assert.equal((await entries('with-role','role-notes',{...role,kind:'concern',status:'completed'}))[0].id,'concern');
  const day = {...role,kind:'day'};
  assert.deepEqual((await entries('with-role','role-notes',day)).map(item => item.dayKind),['fictional','occurred']);
  assert.deepEqual(await entries('with-role','role-notes',{...day,scope:group}),[]);
  const occurred = await entries('with-role','role-notes',{...day,from:at + 2,to:at + 3,dayKind:'occurred'});
  assert.deepEqual(occurred[0].sourceRefs.map(ref => ref.id),['visit']);
  assert.equal((await entries('with-role','role-notes',{...role,scope:group})).length,0);
  assert.equal((await entries('with-role','role-notes',{...role,roleId:'other'})).length,0);
  assert.equal((await entries('plain','continuity-tasks',{scope})).length,1);
  assert.equal((await call('spaces/s/continuity-tasks',{scope,id:'task',operationId:'done',expectedRevision:1,status:'completed'})).status,200);
  assert.equal((await entries('s','continuity-tasks',{scope})).length,0);
});
